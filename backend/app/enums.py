"""Перечисления предметной области.

Значения enum хранятся в PostgreSQL как **нативные типы `enum`**, а не как
строки в `varchar`. Причина практическая: `varchar` принимает любое значение,
и опечатка в коде или в ручном `UPDATE` тихо портит данные, а нативный enum
отвергает такое значение на уровне базы. Второе следствие — появление нового
значения требует миграции, и это видно в истории.
"""

from enum import StrEnum


def enum_values(enum_class: type[StrEnum]) -> list[str]:
    """Значения enum в виде списка строк — так их видит SQLAlchemy.

    ``values_callable`` в SQLAlchemy по умолчанию берёт *имена* членов enum, а не
    их значения — а здесь имя ``INCOME`` и значение ``"income"`` различаются.
    Поэтому список берётся явно: так связь между Python-кодом и типом в базе
    видна сразу, и в базу попадает ровно то, что ожидает код.
    """
    return [member.value for member in enum_class]


class Kind(StrEnum):
    """Вид денежной операции: доход или расход."""

    INCOME = "income"
    EXPENSE = "expense"
